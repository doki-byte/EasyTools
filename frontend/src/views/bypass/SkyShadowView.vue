                  >
                    {{ fn }}
                  </el-tag>
                </template>
              </el-table-column>
            </el-table>
          </template>
        </el-table-column>
        <el-table-column prop="exeName" label="白程序名称" min-width="180" />
        <el-table-column prop="bit" label="位数" width="80" />
        <el-table-column prop="size" label="文件大小" width="120" />
        <el-table-column prop="signed" label="数字签名" width="110" />
        <el-table-column prop="exePath" label="原始路径" min-width="220">
          <template #default="scope">
            <el-tooltip
                :content="scope.row.exePath || ''"
                placement="top"
                :disabled="!scope.row.exePath || scope.row.exePath.length <= 30"
                effect="dark"
            >
              <div class="exe-path-cell">
                {{ scope.row.exePath || '-' }}
              </div>
            </el-tooltip>
          </template>
        </el-table-column>
        <el-table-column label="操作" width="120">
          <template #default="scope">
            <el-button
                type="primary"
                size="small"
                link
                @click="openExeDir(scope.row)"
            >
              打开所在目录
            </el-button>
          </template>
        </el-table-column>
      </el-table>
      <el-pagination
          v-model:current-page="currentPage"
          v-model:page-size="pageSize"
          :page-sizes="[10, 20, 50, 100]"
          :total="filteredPayloads.length"
          layout="total, sizes, prev, pager, next, jumper"
          class="pagination"
          @size-change="handleSizeChange"
          @current-change="handleCurrentChange"
