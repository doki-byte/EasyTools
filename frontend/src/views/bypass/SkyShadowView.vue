                  :disabled="generatingDll || payloadDetails.length === 0"
                  @change="handleAutoGenerateDllChange"
              >
                自动生成测试 DLL(根据选择的语言模板编译)
              </el-checkbox>
            </el-form-item>
          </el-form>
        </div>
      </div>

      <!-- 右侧：运行日志（固定高度，可滚动） -->
      <div class="right-panel">
        <div class="result-card log-card">
          <div class="card-title">运行日志</div>
          <el-input
              type="textarea"
