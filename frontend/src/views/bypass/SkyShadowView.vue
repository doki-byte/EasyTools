<script>
import axios from "axios";
import { GetPortConfig } from "../../../wailsjs/go/controller/Server";

export default {
  name: "SkyShadowView",
  data() {
    return {
      portConfig: null,
      target: "",
      lang: "go",
      verbose: false,
      debug: false,
      loading: false,
      generatingDll: false,
      autoGenerateDll: false,
      output: "",
      payloads: [],
      lastPayloadDir: "",
      payloadDetails: [],
      // 日志与表格轮询定时器
      logTimer: null,
      payloadTimer: null,
      // 表格筛选条件
      keyword: "",
      signedFilter: "all", // all / signed / unsigned
      bitFilter: "all", // all / x64 / x86
      // 分页相关
      currentPage: 1,
      pageSize: 10,
      // 环境状态
      initCheckStatus: "",
    };
  },
  async mounted() {
    await this.loadPortConfig();
    // 初始加载一次现有 Payload 数据
    this.fetchPayloads();
  },
  beforeUnmount() {
    this.stopPolling();
  },
  watch: {
    keyword() {
      this.currentPage = 1;
    },
    signedFilter() {
      this.currentPage = 1;
    },
    bitFilter() {
      this.currentPage = 1;
    },
  },
  computed: {
    filteredPayloads() {
      const kw = this.keyword.trim().toLowerCase();
      return this.payloadDetails.filter((item) => {
        // 关键字匹配：文件名、路径、任意 DLL 名/函数名
        if (kw) {
          const inBasic =
              (item.exeName || "").toLowerCase().includes(kw) ||
              (item.exePath || "").toLowerCase().includes(kw)
          let inDll = false;
          if (item.dlls) {
            for (const d of item.dlls) {
              if (
                  (d.name || "").toLowerCase().includes(kw) ||
                  (d.functions || []).some((fn) =>
                      (fn || "").toLowerCase().includes(kw)
                  )
              ) {
                inDll = true;
                break;
              }
            }
          }
          if (!inBasic && !inDll) return false;
        }

        if (this.signedFilter === "signed" && item.signed !== "有数字签名") {
          return false;
        }
        if (this.signedFilter === "unsigned" && item.signed !== "无数字签名") {
          return false;
        }

        if (this.bitFilter === "x64" && item.bit !== "x64") return false;
        if (this.bitFilter === "x86" && item.bit !== "x86") return false;

        return true;
      });
    },
    paginatedPayloads() {
      const start = (this.currentPage - 1) * this.pageSize;
      const end = start + this.pageSize;
      return this.filteredPayloads.slice(start, end);
    },
  },
  methods: {
    async loadPortConfig() {
      try {
        this.portConfig = await GetPortConfig();
      } catch (error) {
        console.error("获取端口配置失败:", error);
        this.portConfig = {
          mainPort: 52867,
        };
      }
    },
    async handleScan() {
      if (!this.target) {
        this.$message.warning("请先填写扫描路径");
        return;
      }
      const ok = await this.checkEnvReady();
      if (!ok) {
        return;
      }
      if (!this.portConfig) {
        await this.loadPortConfig();
      }
      this.loading = true;
      if (this.output) {
        this.output += "\n";
      }
      this.output += `开始扫描目录：${this.target}\n`;
      this.payloads = [];
      this.lastPayloadDir = "";
      this.payloadDetails = [];
      this.startPolling();
      try {
        const resp = await axios.post(
            `http://127.0.0.1:${this.portConfig.mainPort}/skyshadow/scan`,
            {
              target: this.target,
              lang: this.lang,
              verbose: this.verbose,
              debug: this.debug,
            }
        );
        const data = resp.data;
        if (!data.success) {
          this.$message.error(data.error || "SkyShadow 运行失败");
        } else {
          this.$message.success("SkyShadow 执行完成");
        }
        if (data.output) {
          if (this.output && !this.output.endsWith("\n")) {
            this.output += "\n";
          }
          this.output += data.output;
        }
        this.payloads = (data.payloads || []).map((n) => ({ name: n }));
        this.lastPayloadDir = data.payloadDir || "";
        this.payloadDetails = data.payloadDetails || [];

        // 如果勾选了自动生成 DLL，扫描完成后自动触发
        if (this.autoGenerateDll && this.payloadDetails.length > 0) {
          // 延迟一下，确保 UI 更新完成
          setTimeout(() => {
            this.handleAutoGenerateDllChange(true);
          }, 500);
        }
      } catch (e) {
        console.error(e);
        this.$message.error("请求 SkyShadow 接口失败");
      } finally {
        this.loading = false;
        this.stopPolling();
      }
    },
    async handleCancel() {
      if (!this.loading) return;
      try {
        if (!this.portConfig) {
          await this.loadPortConfig();
        }
        await axios.post(
            `http://127.0.0.1:${this.portConfig.mainPort}/skyshadow/cancel`,
            {}
        );
        this.$message.info("已发送取消请求，正在停止扫描...");
      } catch (e) {
        console.error(e);
        this.$message.error("取消扫描请求失败");
      }
    },
    async openPayloadDir() {
      if (!this.lastPayloadDir) {
        return;
      }
      try {
        // 复用后端 OpenDir 能力，直接打开 SkyShadow Payload 目录
        await axios.get(
            `http://127.0.0.1:${this.portConfig.mainPort}/opendir`,
            {
              params: { path: this.lastPayloadDir },
            }
        );
      } catch (e) {
        console.error(e);
        this.$message.error("打开目录失败");
      }
    },
    startPolling() {
      this.stopPolling();
      if (!this.portConfig) return;
      // 日志轮询
      this.logTimer = setInterval(this.fetchLogs, 1000);
      // 表格数据轮询
      this.payloadTimer = setInterval(this.fetchPayloads, 2000);
    },
    stopPolling() {
      if (this.logTimer) {
        clearInterval(this.logTimer);
        this.logTimer = null;
      }
      if (this.payloadTimer) {
        clearInterval(this.payloadTimer);
        this.payloadTimer = null;
      }
    },
    async fetchLogs() {
      if (!this.portConfig) return;
      try {
        const resp = await axios.get(
            `http://127.0.0.1:${this.portConfig.mainPort}/skyshadow/logs`
        );
        const data = resp.data;
        if (data.success && typeof data.logs === "string") {
          const newLogs = data.logs || "";
          if (!this.output) {
            this.output = newLogs;
          } else if (newLogs && newLogs !== this.output) {
            // 如果后端返回的是完整日志，且以现有内容为前缀，则只追加新增部分
            if (newLogs.startsWith(this.output)) {
              this.output += newLogs.slice(this.output.length);
            } else {
              // 否则直接覆盖，避免无限重复
              this.output = newLogs;
            }
          }
        }
      } catch (e) {
        // 忽略日志拉取错误，避免打扰用户
        console.error("获取 SkyShadow 日志失败:", e);
      }
    },
    async fetchPayloads() {
      if (!this.portConfig) return;
      try {
        const resp = await axios.get(
            `http://127.0.0.1:${this.portConfig.mainPort}/skyshadow/payloads`
        );
        const data = resp.data;
        if (data.success) {
          this.payloads = (data.payloads || []).map((n) => ({ name: n }));
          this.payloadDetails = data.payloadDetails || [];
          if (data.payloadDir) {
            this.lastPayloadDir = data.payloadDir;
          }
        }
      } catch (e) {
        console.error("获取 SkyShadow Payload 列表失败:", e);
      }
    },
    async openExeDir(row) {
      if (!row || !this.portConfig || !this.lastPayloadDir || !row.header) return;
      // 打开 Payload 目录下的对应子目录，例如：EasyToolsFiles\file\skyshadow\Payload\x64 153985.50KB 有数字签名 Clash for Windows.exe
      let dirPath = this.lastPayloadDir;
      if (!dirPath.endsWith("\\") && !dirPath.endsWith("/")) {
        dirPath += "\\";
      }
      dirPath += row.header;
      try {
        await axios.get(
            `http://127.0.0.1:${this.portConfig.mainPort}/opendir`,
            {
              params: { path: dirPath },
            }
        );
      } catch (e) {
        console.error(e);
        this.$message.error("打开 Payload 目录失败");
      }
    },
    handleSizeChange(val) {
      this.pageSize = val;
      this.currentPage = 1;
    },
    handleCurrentChange(val) {
      this.currentPage = val;
    },
    async handleAutoGenerateDllChange(value) {
      if (!value) {
        // 取消勾选，不做任何操作
        return;
      }

      if (this.payloadDetails.length === 0) {
        this.$message.warning('没有可用的程序，请先扫描生成');
        this.autoGenerateDll = false;
        return;
      }

      if (!this.portConfig) {
        await this.loadPortConfig();
      }

      this.$message.warning("正在准备生成测试DLL，请稍等...");

      const ok = await this.checkEnvReady();
      if (!ok) {
        this.autoGenerateDll = false;
        return;
      }

      this.generatingDll = true;
      if (this.output && !this.output.endsWith("\n")) {
        this.output += "\n";
      }
      this.output += `开始为 ${this.payloadDetails.length} 个程序自动生成测试 DLL...\n`;

      try {
        const resp = await axios.post(
          `http://127.0.0.1:${this.portConfig.mainPort}/skyshadow/generateTestDlls`,
          {
            payloads: this.payloadDetails,
            lang: this.lang,
          }
        );

        const data = resp.data;
        if (!data.success) {
          this.$message.error(data.error || '生成测试 DLL 失败');
          this.output += `\n错误: ${data.error || '生成失败'}\n`;
          this.autoGenerateDll = false;
        } else {
          const successCount = data.successCount || 0;
          const failCount = data.failCount || 0;
          this.$message.success(`成功生成 ${successCount} 个 DLL，失败 ${failCount} 个`);
          this.output += `\n生成完成: 成功 ${successCount} 个，失败 ${failCount} 个\n`;
          if (data.details && data.details.length > 0) {
            this.output += '\n生成详情:\n';
            data.details.forEach((detail) => {
              this.output += `  ${detail.dllName}: ${detail.message}\n`;
            });
          }
        }
      } catch (e) {
        console.error(e);
        this.$message.error('请求生成测试 DLL 接口失败');
        this.output += `\n请求失败: ${e.message}\n`;
        this.autoGenerateDll = false;
      } finally {
        this.generatingDll = false;
      }
    },

    // 环境检查入口
    async checkEnvReady() {
      // 环境检测（go/gcc/garble）
      try {
        await axios.get(
            `http://127.0.0.1:${this.portConfig.mainPort}/initCheck`
        );
        this.initCheckStatus = "";
        return true;
      } catch (error) {
        if (
            error.message === "初始化环境失败" ||
            error.response?.status === 404
        ) {
          this.initCheckStatus =
              "环境检测失败：请确认 go、gcc、garble 安装完整，并按文档配置环境变量。";
        } else {
          this.initCheckStatus = "环境检测失败，请检查本地运行环境。";
        }
        // 一段时间后自动清空提示
        setTimeout(() => {
          this.initCheckStatus = "";
        }, 5000);
        return false;
      }
    },
  },
};
</script>

