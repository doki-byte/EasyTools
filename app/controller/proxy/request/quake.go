type QuakeData struct {
	Query string `json:"query"`
	Start int    `json:"start"`
	Size  int    `json:"size"`
}

type QuakeAutoGenerated struct {
	Code    int    `json:"code"`
	Message string `json:"message"`
	Data    []struct {
		Hostname string `json:"hostname"`
		Org      string `json:"org"`
		Port     int    `json:"port"`
		Service  struct {
			Response     string `json:"response"`
			ResponseHash string `json:"response_hash"`
			Name         string `json:"name"`
			Version      string `json:"version"`
			Socks5       struct {
				AuthAcceptedMethod string `json:"auth_accepted_method"`
				Version            int    `json:"version"`
			} `json:"socks5"`
		} `json:"service"`
		Ip        string `json:"ip"`
		OsVersion string `json:"os_version"`
		OsName    string `json:"os_name"`
		Location  struct {
			Owner       string    `json:"owner"`
			ProvinceCn  string    `json:"province_cn"`
			ProvinceEn  string    `json:"province_en"`
			Isp         string    `json:"isp"`
			CountryEn   string    `json:"country_en"`
			DistrictCn  string    `json:"district_cn"`
			Gps         []float64 `json:"gps"`
			StreetCn    string    `json:"street_cn"`
			CityEn      string    `json:"city_en"`
			DistrictEn  string    `json:"district_en"`
			CountryCn   string    `json:"country_cn"`
			StreetEn    string    `json:"street_en"`
			CityCn      string    `json:"city_cn"`
			CountryCode string    `json:"country_code"`
			Asname      string    `json:"asname"`
			SceneCn     string    `json:"scene_cn"`
			SceneEn     string    `json:"scene_en"`
			Radius      int       `json:"radius"`
		} `json:"location"`
		IsIpv6    bool      `json:"is_ipv6"`
		Transport string    `json:"transport"`
		Time      time.Time `json:"time"`
		Asn       int       `json:"asn"`
	} `json:"data"`
	Meta struct {
		Pagination struct {
			Count     int `json:"count"`
			PageIndex int `json:"page_index"`
			PageSize  int `json:"page_size"`
			Total     int `json:"total"`
		} `json:"pagination"`
	} `json:"meta"`
}

func quake_api(keyword string, start int, size int) QuakeData {
	reqData := QuakeData{}
	reqData.Query = keyword
	reqData.Start = start
	reqData.Size = size

	return reqData
}

func quakehttp(postdata QuakeData, key string, timeout string) (*QuakeAutoGenerated, error) {
	var itime, err = strconv.Atoi(timeout)
	if err != nil {
		log.Println("quake超时参数错误: ", err)
		return nil, fmt.Errorf("超时参数错误: %v", err)
	}
	client := proxy.GlobalProxyManager.GetHTTPClient()
	client = &http.Client{
		Timeout:   time.Duration(itime) * time.Second,
		Transport: client.Transport,
	}
	url := "https://quake.360.net/api/v3/search/quake_service"
	payload, _ := json.Marshal(postdata)
	req, err := http.NewRequest("POST", url, bytes.NewBuffer(payload))
	if err != nil {
		log.Println("创建请求失败:", err)
		return nil, fmt.Errorf("创建请求失败: %v", err)
	}
	req.Header.Set("content-type", "application/json")
	req.Header.Set("User-Agent", "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/41.0.2227.0 Safari/537.36")
	req.Header.Set("X-QuakeToken", key)
	resp, err := client.Do(req)
	if err != nil {
		log.Println("HTTP请求失败:", err)
		return nil, fmt.Errorf("HTTP请求失败: %v", err)
	}
	defer resp.Body.Close()
	result, _ := io.ReadAll(resp.Body)
	res := &QuakeAutoGenerated{}
	json.Unmarshal(result, &res)
	return res, nil
}

func Quakeall(keyword string) (urls []string, err error) {
	// 优先从空间测绘配置读取 QuakeKey / timeout / maxPages，回退到 proxy_config.json
	var apiKey string
	var timeout string
	var maxPage string

	if cfg, err := infoCollection.LoadConfigForProxy(); err == nil && cfg != nil {
		if key, ok := cfg.APIKeys["quake"]; ok {
			apiKey = strings.TrimSpace(key)
		}
		if v, ok := cfg.Settings["timeout"]; ok {
			switch vv := v.(type) {
			case float64:
				timeout = strconv.Itoa(int(vv))
			case int:
				timeout = strconv.Itoa(vv)
			case string:
				timeout = vv
			}
		}
		if v, ok := cfg.Settings["maxPages"]; ok {
			switch vv := v.(type) {
			case float64:
				maxPage = strconv.Itoa(int(vv))
			case int:
				maxPage = strconv.Itoa(vv)
			case string:
				maxPage = vv
			}
		}
	}

	quake := config.GetConfig()
	if apiKey == "" {
		apiKey = quake.QuakeKey
	}
	if timeout == "" {
		timeout = quake.Timeout
	}
	if maxPage == "" {
		maxPage = quake.Maxpage
	}

	postdata := quake_api(keyword, 0, 50)
	res, err := quakehttp(postdata, apiKey, timeout)
	if err != nil {
		return nil, fmt.Errorf("quake 第一页请求失败: %v", err)
	}
	pagelength := res.Meta.Pagination.Total/50 + 1
	for _, value := range res.Data {
		urls = append(urls, value.Ip+":"+strconv.Itoa(value.Port))
	}
	Maxpage, _ := strconv.Atoi(maxPage)
	if pagelength > 1 {
		for i := 1; i <= pagelength && i <= Maxpage*2; i++ {
			fmt.Println("quake 正在请求第" + strconv.Itoa(i) + "页数据")
			postdata = quake_api(keyword, i*50, 50)
			res, _ = quakehttp(postdata, apiKey, timeout)
			if len(res.Data) > 0 {
				for _, value := range res.Data {
					urls = append(urls, value.Ip+":"+strconv.Itoa(value.Port))
				}
			} else {
				break
			}
		}
	}

	return urls, nil
}

type QuakeConfig struct{}

func (fp *QuakeConfig) Name() string {
	return "Quake"
}

func (fp *QuakeConfig) Fetch() ([]string, error) {
	// 只根据 Key 是否存在判断是否启用，Key 来源已在 Quakeall 中统一处理
	var hasKey bool
	if cfg, err := infoCollection.LoadConfigForProxy(); err == nil && cfg != nil {
		if key, ok := cfg.APIKeys["quake"]; ok && strings.TrimSpace(key) != "" && cfg.Enabled["quake"] {
			hasKey = true
		}
	}
	if !hasKey {
		quake := config.GetConfig()
		if quake.QuakeKey != "" {
			hasKey = true
		}
	}

	if hasKey {
		var quakekeys string

		cfg := config.GetConfig()
		if cfg.Xui == "1" || cfg.Xui == "2" {
			quakekeys = cfg.QuakeXuiQuery
		} else {
			quakekeys = cfg.QuakeSocks5Query
		}

		urls, err := Quakeall(quakekeys)
		if err != nil {
			log.Printf("Quake搜索失败: %v", err)
			return urls, err
		}
		return urls, nil
	} else {
		return nil, nil
	}
}
