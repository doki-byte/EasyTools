type FofaAutoGenerated struct {
	Mode    string     `json:"mode"`
	Error   bool       `json:"error"`
	Query   string     `json:"query"`
	Page    int        `json:"page"`
	Size    int        `json:"size"`
	Results [][]string `json:"results"`
}

func fofa_api(keyword string, email string, key string, page int, size int) string {
	input := []byte(keyword)
	encodeString := base64.StdEncoding.EncodeToString(input)
	api_request := fmt.Sprintf("https://fofa.info/api/v1/search/all?email=%s&page=%d&size=%d&key=%s&qbase64=%s&fields=ip,host,title,port,protocol", strings.Trim(email, " "), page, size, strings.Trim(key, " "), encodeString)
	return api_request
}

func fofahttp(url string, timeout string) (*FofaAutoGenerated, error) {
	var itime, err = strconv.Atoi(timeout)
	if err != nil {
		log.Println("fofa超时参数错误: ", err)
	}
	client := proxy.GlobalProxyManager.GetHTTPClient()
	client = &http.Client{
		Timeout:   time.Duration(itime) * time.Second,
		Transport: client.Transport,
	}
	req, err := http.NewRequest("GET", url, nil)
	if err != nil {
		log.Println("创建请求失败:", err)
		return nil, fmt.Errorf("创建请求失败: %v", err)
	}
	req.Header.Set("Accept", "*/*;q=0.8")
	req.Header.Set("Connection", "close")
	req.Header.Set("User-Agent", "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/41.0.2227.0 Safari/537.36")
	resp, err := client.Do(req)
	if err != nil {
		log.Println("HTTP请求失败:", err)
		return nil, fmt.Errorf("HTTP请求失败: %v", err)
	}
	defer resp.Body.Close()
	result, _ := io.ReadAll(resp.Body)
	res := &FofaAutoGenerated{}
	json.Unmarshal(result, &res)
	return res, nil
}

// getFofaConfig 优先从空间测绘(info_collection)配置中读取 FOFA 官方 / 第三方配置，
// 支持根据 settings.preferredFofaPlatform 选择具体平台；如果不存在则回退到旧的 proxy_config.json。
// 返回值中 useThird 表示是否使用第三方 FOFA（otherfofa）。
func getFofaConfig() (email string, apiKey string, timeout string, maxPage string, xui string, socksQuery string, xuiQuery string, useThird bool, thirdBaseURL string) {
	// 默认使用 FOFA 官方
	preferred := "fofa"

	// 1. 尝试从空间测绘配置读取
	if cfg, err := infoCollection.LoadConfigForProxy(); err == nil && cfg != nil {
		// 读取偏好设置（如果有）
		if v, ok := cfg.Settings["preferredFofaPlatform"]; ok {
			if s, ok2 := v.(string); ok2 && strings.TrimSpace(s) != "" {
				preferred = strings.TrimSpace(s)
			}
		}

		// 检查官方 / 第三方是否启用
		officialKey, officialHasKey := cfg.APIKeys["fofa"]
		officialEnabled := officialHasKey && cfg.Enabled["fofa"] && strings.TrimSpace(officialKey) != ""

		thirdKey, thirdHasKey := cfg.APIKeys["otherfofa"]
		thirdEnabled := thirdHasKey && cfg.Enabled["otherfofa"] && strings.TrimSpace(thirdKey) != ""

		// 选择实际使用的平台
		switch preferred {
		case "otherfofa":
			if thirdEnabled {
				useThird = true
			} else if officialEnabled {
				useThird = false
			}
		default: // "fofa" 或其他
			if officialEnabled {
				useThird = false
			} else if thirdEnabled {
				useThird = true
			}
		}

		// 按选择的平台读取 key
		if useThird {
			// 第三方 FOFA：只需要 key，不需要 email
			apiKey = strings.TrimSpace(thirdKey)
			// 读取第三方 baseURL
			if v, ok := cfg.Settings["fofaThirdBaseURL"]; ok {
				if s, ok2 := v.(string); ok2 && strings.TrimSpace(s) != "" {
					thirdBaseURL = strings.TrimSpace(s)
				}
			}
		} else if officialEnabled {
			// 官方 FOFA：兼容 email:key 格式
			if strings.Contains(officialKey, ":") {
				parts := strings.SplitN(officialKey, ":", 2)
				email = strings.TrimSpace(parts[0])
				apiKey = strings.TrimSpace(parts[1])
			} else {
				apiKey = strings.TrimSpace(officialKey)
			}
		}

		// 读取超时、最大页数等设置（如果有）
		if v, ok := cfg.Settings["timeout"]; ok {
			switch vv := v.(type) {
			case float64:
				timeout = strconv.Itoa(int(vv))
			case int:
				timeout = strconv.Itoa(vv)
			case string:
				timeout = vv
			}
		}
		if v, ok := cfg.Settings["maxPages"]; ok {
			switch vv := v.(type) {
			case float64:
				maxPage = strconv.Itoa(int(vv))
			case int:
				maxPage = strconv.Itoa(vv)
			case string:
				maxPage = vv
			}
		}
		// 默认第三方 baseURL
		if thirdBaseURL == "" {
			thirdBaseURL = "https://fofa.red"
		}
	}

	// 2. 回退到旧的 proxy_config.json（保持兼容）
	fofa := config.GetConfig()
	if email == "" {
		email = fofa.Email
	}
	if apiKey == "" && !useThird {
		// 只有在使用官方 FOFA 时才从旧配置读取 email/key
		apiKey = fofa.FofaKey
	}
	if timeout == "" {
		timeout = fofa.Timeout
	}
	if maxPage == "" {
		maxPage = fofa.Maxpage
	}
	xui = fofa.Xui
	socksQuery = fofa.FofaSocks5Query
	xuiQuery = fofa.FofaXuiQuery
	return
}

// 生成 FOFA 第三方查询 URL，参考空间测绘的 queryFofaRed 实现
func fofa_third_api(baseURL string, keyword string, key string, page int, size int) string {
	if strings.TrimSpace(baseURL) == "" {
		baseURL = "https://fofa.red"
	}
	baseURL = strings.TrimRight(baseURL, "/") + "/api/v1/search/all"

	encodeString := base64.StdEncoding.EncodeToString([]byte(keyword))
	params := url.Values{}
	params.Set("key", strings.TrimSpace(key))
	params.Set("qbase64", encodeString)
	params.Set("page", strconv.Itoa(page))
	params.Set("size", strconv.Itoa(size))
	params.Set("fields", "ip,host,title,port,protocol")
	params.Set("full", "false")

	return baseURL + "?" + params.Encode()
}

func Fafaall(keyword string) (urls []string, err error) {
	email, apiKey, timeout, maxPage, _, _, _, useThird, thirdBaseURL := getFofaConfig()
	var url string
	if useThird {
		// 使用第三方 FOFA（only key）
		url = fofa_third_api(thirdBaseURL, keyword, apiKey, 1, 100)
	} else {
		// 使用官方 FOFA（email + key）
		url = fofa_api(keyword, email, apiKey, 1, 100)
	}
	res, err := fofahttp(url, timeout)
	if err != nil {
		return nil, fmt.Errorf("fofa 第一页请求失败: %v", err)
	}
	pagelength := res.Size/1000 + 1
	for _, value := range res.Results {
		urls = append(urls, value[1])
	}
	Maxpage, _ := strconv.Atoi(maxPage)
	if pagelength > 1 {
		for i := 2; i <= pagelength && i <= Maxpage; i++ {
			fmt.Println("fofa 正在请求第" + strconv.Itoa(i) + "页数据")
			if useThird {
				url = fofa_third_api(thirdBaseURL, keyword, apiKey, i, 100)
			} else {
				url = fofa_api(keyword, email, apiKey, i, 100)
			}
			res, _ = fofahttp(url, timeout)
			if len(res.Results) > 0 {
				for _, value := range res.Results {
					urls = append(urls, value[1])
				}
			}
		}
	}

	return urls, nil
}

type FofaConfig struct {
}

func (fp *FofaConfig) Name() string {
	return "Fofa"
}

func (fp *FofaConfig) Fetch() ([]string, error) {
	email, apiKey, _, _, xui, socksQuery, xuiQuery, useThird, _ := getFofaConfig()
	// 官方 FOFA 需要 email + key，第三方只需要 key
	hasKey := apiKey != ""
	if !useThird && email == "" {
		hasKey = false
	}

	if hasKey {
		var fofakeys string

		if xui == "1" || xui == "2" {
			fofakeys = xuiQuery
		} else {
			fofakeys = socksQuery
		}

		urls, err := Fafaall(fofakeys)
		if err != nil {
			log.Printf("fofa搜索失败: %v", err)
			return urls, err
		}
		return urls, nil
	} else {
		return nil, nil
	}
}
