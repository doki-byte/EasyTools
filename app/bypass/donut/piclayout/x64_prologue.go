func tryX64Prologue(pic []byte) (instOff, instLen int, ok bool) {
	for _, v := range X64PrologueVariants {
		bodyLen := len(v.Prefix) - 5
		if bodyLen < 0 || len(pic) < v.InstOff {
			continue
		}
		if !bytes.Equal(pic[:bodyLen], v.Prefix[:bodyLen]) {
			continue
		}
		if pic[bodyLen] != 0xE9 {
			continue
		}
		if n, okInst := validateInstanceAt(pic, v.InstOff); okInst {
			return v.InstOff, n, true
		}
	}
	return 0, 0, false
}
